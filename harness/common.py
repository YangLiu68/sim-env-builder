ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "plugin"
SKILL = PLUGIN / "skills/sim-env-builder"
GOLDEN = ROOT / "golden"
RUNS = GOLDEN / "runs"
STUDIO_RUNS = ROOT / "dashboard/runs"   # runs started from the dashboard
MCP_CONFIG = ROOT / "harness/.generated/mcp.json"  # generated by mcp_config_for()
VENV_PY = ROOT / ".venv/bin/python"
CLAUDE = os.environ.get("CLAUDE_BIN", "claude")
MODEL = os.environ.get("GOLDEN_MODEL", "opus")
EFFORT = os.environ.get("GOLDEN_EFFORT", "xhigh")

# ----------------------------------------------------------------------------- provider
# Agents run on the Claude Code login by default. With an OpenRouter key they run through
# OpenRouter's Anthropic-compatible endpoint instead (pay-per-token on that account).
#   key:      OPENROUTER_API_KEY env var, or ~/.config/onellmpj/openrouter.env  (OPENROUTER_API_KEY=...)
#   switch:   GOLDEN_PROVIDER=openrouter | claude | auto (default auto: OpenRouter when a key exists)
OPENROUTER_KEY_FILE = Path.home() / ".config/onellmpj/openrouter.env"
OPENROUTER_BASE = "https://openrouter.ai/api"
OPENROUTER_MODELS = {"opus": "anthropic/claude-opus-5.5", "sonnet": "anthropic/claude-sonnet-5.5",
                     "haiku": "anthropic/claude-haiku-5.5", "fable": "anthropic/claude-fable-5.2"}


def openrouter_key() -> str | None:
    k = os.environ.get("OPENROUTER_API_KEY", "").strip()
    if k:
        return k
    try:
        for line in OPENROUTER_KEY_FILE.read_text().splitlines():
            if line.strip().startswith("OPENROUTER_API_KEY="):
                return line.split("=", 1)[1].strip().strip("'\"") or None
    except OSError:
        return None
    return None


MIN_CREDITS_USD = float(os.environ.get("GOLDEN_MIN_CREDITS", "15"))  # one golden task costs ~$5-7
_credit_cache: dict = {}


def openrouter_credits() -> float | None:
    """Remaining OpenRouter balance in USD (cached 5 min), or None if it cannot be read."""
    key = openrouter_key()
    if not key:
        return None
    hit = _credit_cache.get("v")
    if hit and time.time() - hit[0] < 300:
        return hit[1]
    try:
        import urllib.request

        req = urllib.request.Request("https://openrouter.ai/api/v1/credits", headers={"Authorization": f"Bearer {key}"})
        d = json.loads(urllib.request.urlopen(req, timeout=20).read()).get("data", {})
        left = float(d.get("total_credits", 0)) - float(d.get("total_usage", 0))
    except Exception:  # noqa: BLE001
        left = None
    _credit_cache["v"] = (time.time(), left)
    return left


def provider() -> str:
    """claude (Claude Code login) or openrouter. auto = OpenRouter only with a key AND enough credit."""
    want = os.environ.get("GOLDEN_PROVIDER", "claude").lower()  # OpenRouter is opt-in: GOLDEN_PROVIDER=openrouter or auto
    if want == "claude" or not openrouter_key():
        if want == "openrouter":
            raise RuntimeError(f"GOLDEN_PROVIDER=openrouter but no key in OPENROUTER_API_KEY or {OPENROUTER_KEY_FILE}")
        return "claude"
    if want == "openrouter":
        return "openrouter"
    left = openrouter_credits()
    return "openrouter" if (left is not None and left >= MIN_CREDITS_USD) else "claude"


def agent_env(base: dict | None = None) -> tuple[dict, str]:
    """Environment + model name for a headless claude process under the active provider."""
    env = dict(base if base is not None else os.environ)
    env.pop("CLAUDECODE", None)  # allow nesting a fresh claude under this session
    env.setdefault("SIMENV_HOME", str(Path.home() / ".cache/sim-env-builder"))
    model = MODEL
    if provider() == "openrouter":
        env["ANTHROPIC_BASE_URL"] = OPENROUTER_BASE
        env["ANTHROPIC_AUTH_TOKEN"] = openrouter_key()
        env["ANTHROPIC_API_KEY"] = ""  # make sure the OpenRouter token is the credential used
        model = OPENROUTER_MODELS.get(MODEL, MODEL)
    return env, model


def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(f"{path.suffix}.{os.getpid()}.{uuid.uuid4().hex[:8]}.tmp")  # unique: threads write concurrently
    tmp.write_text(json.dumps(obj, indent=1, default=str))
    os.replace(tmp, path)


def read_json(path: Path, default=None):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return default


def set_status(run_dir: Path, **kw) -> dict:
    st = read_json(run_dir / "status.json", {}) or {}
    st.update(kw, updated=time.time())
    write_json(run_dir / "status.json", st)
    return st


def mcp_config_for(plugin: Path) -> Path:
    """MCP config that starts the Poly Pizza server from ``plugin`` (live plugin or a frozen snapshot).
    Generated at runtime (absolute paths are machine-specific, so nothing is committed)."""
    cfg = MCP_CONFIG if Path(plugin).resolve() == PLUGIN.resolve() else Path(plugin).parent / "mcp.json"
    write_json(cfg, {"mcpServers": {"polypizza": {"command": str(Path(plugin).resolve() / "bin/polypizza-mcp"), "args": [],
                                                  "env": {"POLYPIZZA_PYTHON": str(VENV_PY)}}}})
    return cfg


def agent_cmd(prompt: str, session_id: str, resume: bool, tools: str | None = None, extra: list[str] | None = None,
              plugin: Path | None = None, model: str | None = None) -> list[str]:
    plugin = Path(plugin or PLUGIN)
    model = model or agent_env()[1]
    cmd = [CLAUDE, "-p", prompt,
           "--plugin-dir", str(plugin),
           "--mcp-config", str(mcp_config_for(plugin)), "--strict-mcp-config",
           "--setting-sources", "project",
           "--no-chrome",
           "--dangerously-skip-permissions",
           "--disallowedTools", "AskUserQuestion",
           "--output-format", "stream-json", "--verbose",
           "--model", model, "--effort", EFFORT]
    cmd += ["--resume", session_id] if resume else ["--session-id", session_id]
    if tools:
        cmd += ["--tools", tools]
    return cmd + (extra or [])


CONTINUE_AFTER_OUTAGE = ("The connection to the API dropped for a while. It is back now. Continue exactly where you "
                         "left off and finish the current request.")
TRANSIENT = ("connection_failed", "overloaded", "rate_limit", "api_timeout", "server_error")


def network_ok() -> bool:
    try:
        import urllib.request

        urllib.request.urlopen("https://api.anthropic.com", timeout=10)
        return True
    except Exception as e:  # noqa: BLE001 - an HTTP error status still means the host is reachable
        return hasattr(e, "code")


def wait_for_usage_reset(message: str, max_wait_s: int = 6 * 3600) -> None:
    """Sleep until the reset time in "You've hit your 5-hour limit · resets 4:30pm (...)" (+2 min);
    if it cannot be parsed, wait 30 min. Never longer than ``max_wait_s``."""
    import datetime as dt
    import re

    wait = 1800.0
    m = re.search(r"resets\s+(\d{1,2})(?::(\d{2}))?\s*([ap]m)", message or "", re.I)
    if m:
        h, mi, ap = int(m.group(1)), int(m.group(2) or 0), m.group(3).lower()
        h = h % 12 + (12 if ap == "pm" else 0)
        now = dt.datetime.now()
        reset = now.replace(hour=h, minute=mi, second=0, microsecond=0)
        if reset <= now:
            reset += dt.timedelta(days=1)
        wait = (reset - now).total_seconds() + 120
    time.sleep(min(max(wait, 60), max_wait_s))


def wait_for_network(max_wait_s: int = 3600, log=None) -> bool:
    t0 = time.time()
    while time.time() - t0 < max_wait_s:
        if network_ok():
            return True
        if log:
            log(f"network down, waiting ({int(time.time() - t0)} s)")
        time.sleep(30)
    return False


def run_agent(workdir: Path, prompt: str, session_id: str | None = None, resume: bool = False, shot: int = 1,
              transcript: Path | None = None, timeout_s: int = 5400, tools: str | None = None, extra=None,
              plugin: Path | None = None, max_retries: int = 8) -> dict:
    """One user turn, robust to API/network outages: on a transient API error the harness waits
    for the network and resumes the same session with a "continue" message (up to max_retries).
    ``cost_usd`` is the session's cumulative cost as reported by Claude Code."""
    session_id = session_id or str(uuid.uuid4())
    t0 = time.time()
    out = _run_once(workdir, prompt, session_id, resume, shot, transcript, timeout_s, tools, extra, plugin)
    retries = 0
    while out.get("transient") and retries < max_retries:
        retries += 1
        if out.get("usage_limit"):
            wait_for_usage_reset(out.get("result", ""))
        else:
            wait_for_network()
            time.sleep(20)
        did_work = out.get("num_turns", 0) > 1
        out = _run_once(workdir, CONTINUE_AFTER_OUTAGE if did_work else prompt, session_id, True, shot, transcript,
                        timeout_s, tools, extra, plugin)
    out["retries"] = retries
    out["duration_s"] = round(time.time() - t0, 1)
    return out


def _run_once(workdir: Path, prompt: str, session_id: str, resume: bool, shot: int, transcript: Path | None,
              timeout_s: int, tools: str | None, extra, plugin: Path | None) -> dict:
    workdir.mkdir(parents=True, exist_ok=True)
    session_id = session_id or str(uuid.uuid4())
    transcript = transcript or (workdir / "transcript.jsonl")
    env, model = agent_env()
    t0 = time.time()
    out = {"session_id": session_id, "result": "", "cost_usd": 0.0, "num_turns": 0, "is_error": False, "timed_out": False,
           "provider": provider(), "model": model}
    with open(transcript, "a") as log:
        log.write(json.dumps({"type": "harness", "event": "shot_start", "shot": shot, "prompt": prompt, "t": t0}) + "\n")
        log.flush()
        p = subprocess.Popen(agent_cmd(prompt, session_id, resume, tools, extra, plugin, model), cwd=str(workdir), env=env,
                             stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
        try:
            for line in p.stdout:
                line = line.rstrip("\n")
                if not line:
                    continue
                try:
                    ev = json.loads(line)
                except ValueError:
                    ev = {"type": "raw", "text": line}
                ev["_shot"] = shot
                ev["_t"] = time.time()
                log.write(json.dumps(ev) + "\n")
                log.flush()
                if ev.get("type") == "result":
                    api_err = str(ev.get("api_error") or "")
                    out.update(result=ev.get("result") or "", cost_usd=ev.get("total_cost_usd") or 0.0,
                               num_turns=ev.get("num_turns") or 0, is_error=bool(ev.get("is_error")),
                               transient=bool(ev.get("is_error")) and (api_err in TRANSIENT or "Can't reach the API" in str(ev.get("result")))
                               or ev.get("terminal_reason") == "api_error",
                               usage_limit=api_err == "usage_limit_reached" or "hit your" in str(ev.get("result", "")) and "limit" in str(ev.get("result", "")))
                if time.time() - t0 > timeout_s:
                    p.kill()
                    out["timed_out"] = True
                    break
            p.wait(timeout=60)
        except Exception as e:  # noqa: BLE001
            p.kill()
            out["is_error"] = True
            out["result"] = f"harness error: {e!r}"
        log.write(json.dumps({"type": "harness", "event": "shot_end", "shot": shot, "t": time.time(), **{k: v for k, v in out.items() if k != 'result'}}) + "\n")
    out["duration_s"] = round(time.time() - t0, 1)
    return out


def find_env_dir(workdir: Path) -> Path | None:
    """The environment folder: the shallowest directory containing scene.xml (skips simkit copies)."""
    hits = sorted((p for p in workdir.rglob("scene.xml") if "smoke" not in p.parts and ".venv" not in p.parts),
                  key=lambda p: len(p.parts))
    return hits[0].parent if hits else None
